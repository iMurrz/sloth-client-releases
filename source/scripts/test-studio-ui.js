// Electron integration check. Uses an isolated temporary profile and synthetic game data.
const { app } = require('electron');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'sloth-ui-'));
fs.mkdirSync(path.join(profile, 'launcher'));
app.setPath('appData', profile);
app.setPath('userData', path.join(profile, 'launcher'));
const gameDir = path.join(profile, '.sloth', 'instances', 'sloth');
fs.mkdirSync(path.join(gameDir, 'saves', 'Demo survival'), { recursive: true });
fs.mkdirSync(path.join(gameDir, 'mods'));
fs.writeFileSync(path.join(gameDir, 'saves', 'Demo survival', 'level.dat'), 'synthetic world');
fs.writeFileSync(path.join(gameDir, 'mods', 'demo.jar'), 'synthetic mod');
fs.writeFileSync(path.join(gameDir, 'options.txt'), 'resourcePacks:["vanilla"]');
const { LaunchHistory } = require('../src/lib/launch-history');
const history = new LaunchHistory(path.join(profile, '.sloth'));
const sessionId = history.start({ id: 'sloth', name: 'Sloth' }, { version: '1.21.11', memoryMb: 4096, capture: true });
history.finish(sessionId, { code: 0, crashed: false, stopped: false });
const out = path.join(__dirname, '..', 'snapshots', 'studio-upgrade');
fs.mkdirSync(out, { recursive: true });
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
const errors = [];
app.on('browser-window-created', (_event, win) => {
  win.webContents.setBackgroundThrottling(false);
  win.webContents.on('console-message', event => { if (event.level === 'error') errors.push(event.message); });
  win.webContents.once('did-finish-load', async () => {
    try {
      await wait(1200);
      const run = script => win.webContents.executeJavaScript(script);
      await run('window.confirm=()=>true;true'); // Consent applies only to synthetic fixture files.
      const capture = async name => {
        await run('Promise.race([new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))),new Promise(resolve=>setTimeout(resolve,1500))])');
        await wait(250);
        fs.writeFileSync(path.join(out, name), (await win.webContents.capturePage()).toPNG());
      };
      const manager = require('../src/lib/mod-manager');
      console.log('Studio check: mod fixtures');
      const fixtureRoot = path.join(profile, 'mod-fixtures');
      fs.mkdirSync(fixtureRoot);
      const fixture = path.join(fixtureRoot, 'local-fabric.jar');
      fs.copyFileSync(path.join(__dirname, '..', 'client-mod', 'build', 'libs', 'sloth-client-1.1.0.jar'), fixture);
      const imported = await manager.importFiles(gameDir, [fixture]);
      assert.deepEqual(imported.imported, ['local-fabric.jar']);
      assert.equal((await manager.importFiles(gameDir, [fixture])).skipped.length, 1);
      const fixtureHash = await manager.fingerprint(gameDir, 'local-fabric.jar');
      await manager.toggle(gameDir, 'local-fabric.jar', false);
      assert.equal(await manager.fingerprint(gameDir, 'local-fabric.jar.disabled'), fixtureHash);
      fs.copyFileSync(fixture, path.join(gameDir, 'mods', 'local-fabric.jar'));
      await assert.rejects(manager.toggle(gameDir, 'local-fabric.jar.disabled', true), /Another copy/);
      const duplicate = await manager.inspect(gameDir, '1.21.11', '0.19.5');
      fs.copyFileSync(fixture, path.join(gameDir, 'mods', 'second-fabric.jar'));
      assert.ok((await manager.inspect(gameDir, '1.21.11', '0.19.5')).mods.some(mod => mod.issues.some(issue => issue.includes('Duplicate mod ID'))));
      assert.equal(duplicate.mods.find(mod => mod.filename === 'local-fabric.jar').id, 'sloth-client');
      fs.writeFileSync(path.join(gameDir, 'mods', '.sloth-managed.json'), JSON.stringify({ files: ['second-fabric.jar'] }));
      await assert.rejects(manager.toggle(gameDir, 'second-fabric.jar', false), /launcher-provided/);
      // Remove only files owned by this synthetic fixture, keeping the UI's original one-mod scenario.
      for (const name of ['local-fabric.jar', 'local-fabric.jar.disabled', 'second-fabric.jar', '.sloth-managed.json']) fs.unlinkSync(path.join(gameDir, 'mods', name));
      await run("document.querySelector('[data-download-page=packs]').click()");
      console.log('Studio check: download center');
      await wait(350);
      assert.ok((await run("document.querySelector('#page-packs').textContent")).includes('Modrinth'));
      assert.equal(await run("document.querySelector('#curseforge-key')"), null);
      await capture('modpack-library.png');
      await run("document.querySelector('[data-download-page=mods]').click()");
      await wait(600);
      assert.ok((await run("document.querySelector('#mods-results').textContent")).includes('demo.jar'));
      assert.ok((await run("document.querySelector('#mods-results').textContent")).includes('Cannot read'));
      await run("Array.from(document.querySelectorAll('#mods-results button')).find(button => button.textContent === 'Disable').click()");
      await wait(500);
      assert.ok(fs.existsSync(path.join(gameDir, 'mods', 'demo.jar.disabled')));
      assert.equal(fs.existsSync(path.join(gameDir, 'mods', 'demo.jar')), false);
      await run("Array.from(document.querySelectorAll('#mods-results button')).find(button => button.textContent === 'Enable').click()");
      await wait(500);
      assert.equal(fs.readFileSync(path.join(gameDir, 'mods', 'demo.jar'), 'utf8'), 'synthetic mod');
      await run("Array.from(document.querySelectorAll('#mods-results button')).find(button => button.textContent === 'File fingerprint').click()");
      await wait(400);
      assert.match(await run("document.querySelector('.mod-fingerprint').textContent"), /SHA-256: [a-f0-9]{64}/);
      assert.equal(await run("(async () => { try { await window.sloth.modsToggle({ filename: '../escape.jar', enabled: false }); return false; } catch { return true; } })()"), true);
      await capture('mod-manager.png');
      await run("document.querySelector('[data-page=history]').click()");
      await wait(400);
      assert.ok((await run("document.querySelector('#history-results').textContent")).includes('completed'));
      await capture('launch-history.png');
      await run("document.querySelector('[data-studio-page=workshop]').click()");
      await wait(900);
      assert.equal(await run("document.querySelectorAll('#studio-checks article').length"), 5);
      await capture('setup-studio.png');
      await run("document.querySelector('#studio-storage').scrollIntoView({ block: 'center' })");
      await capture('storage.png');
      await run("document.querySelector('[data-preset=visual]').click()");
      await wait(250);
      await run("Array.from(document.querySelectorAll('.change-review-dialog button')).find(b=>b.textContent.startsWith('Apply'))?.click()");
      await wait(700);
      assert.equal(await run('(async () => (await window.sloth.bootstrap()).settings.mods.iris)()'), true);
      await run("document.querySelector('[data-page=instances]').click(); document.querySelector('.instance-tools button').click()");
      await wait(400);
      assert.equal(await run('(async () => (await window.sloth.bootstrap()).instances[0].favorite)()'), true);
      await run("document.querySelectorAll('.instance-tools button')[1].click(); document.querySelector('#rename-name').value = 'Survival collection'; document.querySelector('#rename-form').requestSubmit()");
      await wait(400);
      assert.equal(await run("document.querySelector('#active-instance-label').textContent"), 'Survival collection');
      await run("document.querySelector('#instance-search').value = 'no such instance'; document.querySelector('#instance-search').dispatchEvent(new Event('input'))");
      assert.ok((await run("document.querySelector('#instance-grid').textContent")).includes('No instances match'));
      await run("document.querySelector('#instance-search').value = ''; document.querySelector('#instance-search').dispatchEvent(new Event('input'))");
      await capture('instances.png');
      await run("document.querySelector('[data-toolbox-page=recovery]').click()");
      await wait(300);
      await run("document.querySelector('#recovery-label').value = 'Before new mods'; document.querySelector('#recovery-save').click()");
      await wait(900);
      assert.equal(await run("document.querySelectorAll('#recovery-list article').length"), 1);
      await capture('recovery.png');
      await run("document.querySelector('#recovery-list button').click()");
      await wait(1000);
      assert.ok((await run("document.querySelector('#active-instance-label').textContent")).includes('restored'));
      const concurrency = await run(`(async () => {
        const save = window.sloth.recoveryCreate('Concurrent operation');
        let rejected = false;
        try { await window.sloth.editInstance({ id: (await window.sloth.bootstrap()).activeInstanceId, name: 'Should not apply' }); } catch { rejected = true; }
        await save;
        return rejected;
      })()`);
      assert.equal(concurrency, true);
      await run("document.dispatchEvent(new KeyboardEvent('keydown', { key: 'k', ctrlKey: true })); document.querySelector('#quick-search').value = 'Setup Studio'; document.querySelector('#quick-search').dispatchEvent(new Event('input'))");
      assert.equal(await run("document.querySelectorAll('#quick-results button').length"), 1);
      assert.equal(await run("document.querySelector('#quick-modal').hidden"), false);
      await capture('quick-actions.png');
      await run("document.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter' }))");
      assert.equal(await run("document.querySelector('#page-workshop').classList.contains('active')"), true);
      await run("document.querySelector('[data-page=updates]').click(); document.querySelector('#update-page-check').click()");
      await wait(300);
      assert.equal(await run("document.querySelector('#update-state-label').textContent"), 'DEVELOPMENT BUILD');
      assert.equal(await run("document.querySelector('#update-page-check').disabled"), false);
      await run("renderUpdate({ state: 'downloading', version: '9.9.9', percent: 42 })");
      assert.equal(await run("document.querySelector('#update-download-progress').value"), 42);
      assert.equal(await run("document.querySelector('#update-page-check').disabled"), true);
      await run("renderUpdate({ state: 'ready', version: '9.9.9' })");
      assert.equal(await run("document.querySelector('#update-page-install').hidden"), false);
      await run("renderUpdate({ state: 'unconfigured' })");
      assert.equal(await run("document.querySelector('#update-page-install').hidden"), true);
      await capture('update-launcher.png');
      assert.deepEqual(errors, []);
      console.log('PASS local import, duplicate IDs, file preservation, protected mods, real IPC/UI mod toggles and fingerprints, launch history, presets, favourites, recovery, concurrency and quick actions.');
      console.log(`Screenshots: ${out}`);
      app.exit(0);
    } catch (error) { console.error(error); app.exit(1); }
  });
});
// The launcher owns this process from here. No Microsoft login or real Minecraft launch is attempted.
require('../src/main');
